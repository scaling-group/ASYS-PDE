"""Render Eve's local helper agents for Claude Code."""

from __future__ import annotations

import json
from pathlib import Path

from scaling_evolve.algorithms.eve.workspace.opencode_agents import (
    read_codex_agent_definitions,
)

_GENERATED_MARKER = "<!-- Generated by EvE from .codex/agents; edit the TOML source instead. -->"


def project_claude_agents(workspace: Path, *, config_root: Path) -> None:
    """Project helper agents as project-scope Claude Code subagents.

    The `.codex/agents/*.toml` definitions stay the single source; each one is rendered
    to `<config_root>/agents/<name>.md` and inherits the session's model. Only files
    rendered here are replaced or removed.
    """

    source_root = workspace / ".codex" / "agents"
    target_root = config_root / "agents"
    definitions = read_codex_agent_definitions(source_root) if source_root.is_dir() else {}

    if target_root.is_dir():
        for stale_path in target_root.glob("*.md"):
            if _GENERATED_MARKER in stale_path.read_text(encoding="utf-8"):
                stale_path.unlink()
    if not definitions:
        return
    target_root.mkdir(parents=True, exist_ok=True)
    for name, (description, prompt) in definitions.items():
        target = target_root / f"{name}.md"
        if target.exists():
            continue
        rendered = "\n".join(
            [
                "---",
                f"name: {name}",
                f"description: {json.dumps(description, ensure_ascii=False)}",
                "model: inherit",
                "---",
                "",
                _GENERATED_MARKER,
                "",
                prompt.strip(),
                "",
            ]
        )
        target.write_text(rendered, encoding="utf-8")
